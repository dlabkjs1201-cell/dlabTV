def update_calendar():
    try:
        month_text = month_entry.get()
        month = int(month_text)
        if not (1 <= month <= 12):
            return
    except ValueError:
        return

    # 기존 달력 위젯 삭제
    for widget in calendar_frame.winfo_children():
        widget.destroy()

    # 2026년 기준 달력 데이터 생성
    cal = calendar.monthcalendar(2026, month)

    # 요일 헤더 생성
    days = ['일', '월', '화', '수', '목', '금', '토']
    for i, day in enumerate(days):
        lbl = tk.Label(calendar_frame, text=day, font=("맑은 고딕", 12, "bold"), width=8)
        lbl.grid(row=0, column=i, pady=10)

    # 날짜 버튼 생성
    for row_idx, week in enumerate(cal):
        for col_idx, day in enumerate(week):
            if day != 0:
                btn = tk.Button(calendar_frame, text=str(day), width=6, height=3,
                                font=("맑은 고딕", 11),
                                command=lambda m=month, d=day: check_history(m, d))
                btn.grid(row=row_idx + 1, column=col_idx, padx=3, pady=3)


